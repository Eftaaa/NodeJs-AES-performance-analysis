uint32_t InvSubWord(uint32_t w)
{
	uint8_t byte0 = InvSBox((w >> 24) & 0xFF);
	uint8_t byte1 = InvSBox((w >> 16) & 0xFF);
	uint8_t byte2 = InvSBox((w >> 8) & 0xFF);
	uint8_t byte3 = InvSBox(w & 0xFF);
	return ((uint32_t)byte0 << 24) | ((uint32_t)byte1 << 16) | ((uint32_t)byte2 << 8) | byte3;
}
uint32_t InvRotWord(uint32_t w)
{
	uint8_t  temp;
	temp = (w >> 24) & 0xFF;
	w = w << 8;
	w = w | temp;
	return w;
}




void InvSubBytes(uint8_t** s)
{
	for (int i = 0; i < 4; i++)
	{
		for (int j = 0; j < 4; j++)
		{
			s[i][j] = InvSBox(s[i][j]);
		}
	}
}
void InvShiftRows(uint8_t** s)
{
	swap(s[3][0], s[3][3]);
	swap(s[3][0], s[3][2]);
	swap(s[3][0], s[3][1]);
	swap(s[2][1], s[2][3]);
	swap(s[2][0], s[2][2]);
	swap(s[1][2], s[1][3]);
	swap(s[1][1], s[1][2]);
	swap(s[1][0], s[1][1]);
}









